"""Base model definitions, UTC DateTime decorator, and audit timestamp mixins."""

from datetime import datetime, timezone
from sqlalchemy import DateTime, TypeDecorator
from sqlalchemy.orm import Mapped, mapped_column
from backend.app.core.database import Base


class UTCDateTime(TypeDecorator):
    """Ensures datetimes are always stored as UTC and returned timezone-aware."""

    impl = DateTime
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is not None:
            if value.tzinfo is None:
                value = value.replace(tzinfo=timezone.utc)
            else:
                value = value.astimezone(timezone.utc)
        return value

    def process_result_value(self, value, dialect):
        if value is not None:
            if value.tzinfo is None:
                value = value.replace(tzinfo=timezone.utc)
            else:
                value = value.astimezone(timezone.utc)
        return value


class TimestampMixin:
    """Provides created_at and updated_at UTC timestamps for models."""

    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime,
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
